package com.kodegladiators.kaasutracker;

import static org.junit.jupiter.api.Assertions.assertEquals;

import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

class FinancialMigrationTests {

    @Test
    void migrationPreservesExistingExpenseRowsAndAddsFinanceTables() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:finance-migration;MODE=PostgreSQL;DB_CLOSE_DELAY=-1",
                "sa",
                ""
        );
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                CREATE TABLE app_users (
                    id VARCHAR(255) PRIMARY KEY
                )
                """);
        jdbc.execute("""
                CREATE TABLE expenses (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id VARCHAR(255) NOT NULL REFERENCES app_users(id),
                    expense_date DATE NOT NULL DEFAULT CURRENT_DATE
                )
                """);
        jdbc.execute("""
                CREATE TABLE emis (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title VARCHAR(150) NOT NULL,
                    amount NUMERIC(12, 2) NOT NULL,
                    due_date_day INTEGER NOT NULL,
                    duration_months INTEGER NOT NULL DEFAULT 12,
                    is_active BOOLEAN NOT NULL DEFAULT TRUE,
                    user_id VARCHAR(255) NOT NULL REFERENCES app_users(id)
                )
                """);
        jdbc.update("INSERT INTO app_users (id) VALUES (?)", "migration-user");
        jdbc.update("INSERT INTO expenses (user_id) VALUES (?)", "migration-user");
        jdbc.update("""
                INSERT INTO emis (title, amount, due_date_day, duration_months, is_active, user_id)
                VALUES ('Legacy EMI', 100.00, 31, 12, TRUE, 'migration-user')
                """);
        jdbc.update("""
                INSERT INTO emis (title, amount, due_date_day, duration_months, is_active, user_id)
                VALUES ('Inactive legacy EMI', 50.00, 15, 24, FALSE, 'migration-user')
                """);

        Flyway.configure()
                .dataSource(dataSource)
                .locations("classpath:db/migration")
                .baselineOnMigrate(true)
                .baselineVersion("0")
                .load()
                .migrate();

        assertEquals(1L, jdbc.queryForObject("SELECT COUNT(*) FROM expenses", Long.class));
        assertEquals(
                new java.math.BigDecimal("0.00"),
                jdbc.queryForObject("SELECT refunded_amount FROM expenses WHERE id = 1", java.math.BigDecimal.class)
        );
        assertEquals(0L, jdbc.queryForObject("SELECT COUNT(*) FROM monthly_salaries", Long.class));
        assertEquals(1L, jdbc.queryForObject(
                "SELECT COUNT(*) FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'ADDITIONAL_FUNDS'",
                Long.class
        ));
        assertEquals(1L, jdbc.queryForObject(
                "SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS "
                        + "WHERE TABLE_NAME = 'EXPENSE_FUNDING_ALLOCATIONS' "
                        + "AND COLUMN_NAME = 'ADDITIONAL_FUND_ID'",
                Long.class
        ));
        assertEquals(0L, jdbc.queryForObject("SELECT COUNT(*) FROM emi_installments", Long.class));
        assertEquals(1L, jdbc.queryForObject(
                "SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS "
                        + "WHERE TABLE_NAME = 'EXPENSES' AND COLUMN_NAME = 'EMI_INSTALLMENT_ID'",
                Long.class
        ));
        assertEquals(1L, jdbc.queryForObject(
                "SELECT COUNT(*) FROM INFORMATION_SCHEMA.INDEXES "
                        + "WHERE INDEX_NAME = 'IX_EXPENSES_USER_DATE_ID'",
                Long.class
        ));
        assertEquals(1L, jdbc.queryForObject(
                "SELECT COUNT(*) FROM INFORMATION_SCHEMA.INDEXES "
                        + "WHERE INDEX_NAME = 'IX_EMIS_USER_ACTIVE'",
                Long.class
        ));
        assertEquals(1L, jdbc.queryForObject(
                "SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS "
                        + "WHERE TABLE_NAME = 'EXPENSES' AND COLUMN_NAME = 'IDEMPOTENCY_KEY'",
                Long.class
        ));
        assertEquals(1L, jdbc.queryForObject(
                "SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS "
                        + "WHERE TABLE_NAME = 'EXPENSES' AND COLUMN_NAME = 'FUNDING_ALLOCATION_MANUAL'",
                Long.class
        ));
        assertEquals(1L, jdbc.queryForObject(
                "SELECT COUNT(*) FROM expenses WHERE funding_allocation_manual = FALSE",
                Long.class
        ));
        assertEquals(1L, jdbc.queryForObject(
                "SELECT COUNT(*) FROM INFORMATION_SCHEMA.INDEXES "
                        + "WHERE INDEX_NAME = 'UK_EXPENSES_USER_IDEMPOTENCY_KEY'",
                Long.class
        ));
        assertEquals(1L, jdbc.queryForObject(
                "SELECT COUNT(*) FROM INFORMATION_SCHEMA.INDEXES "
                        + "WHERE INDEX_NAME = 'IX_BORROWED_FUNDS_USER_STATUS_DATE'",
                Long.class
        ));
        assertEquals(1L, jdbc.queryForObject(
                "SELECT COUNT(*) FROM emis WHERE status = 'ACTIVE' AND duration_known = FALSE "
                        + "AND end_date IS NULL AND total_installments IS NULL",
                Long.class
        ));
        assertEquals(1L, jdbc.queryForObject(
                "SELECT COUNT(*) FROM emis WHERE status = 'INACTIVE' AND duration_known = FALSE "
                        + "AND duration_months = 24 AND total_installments IS NULL",
                Long.class
        ));
    }
}
