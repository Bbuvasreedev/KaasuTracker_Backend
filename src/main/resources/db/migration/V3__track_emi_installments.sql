CREATE TABLE IF NOT EXISTS emis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    due_date_day INTEGER NOT NULL,
    duration_months INTEGER NOT NULL DEFAULT 12,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    user_id VARCHAR(255) NOT NULL REFERENCES app_users(id) ON DELETE CASCADE
);

ALTER TABLE emis
    ADD COLUMN IF NOT EXISTS started_on DATE;

UPDATE emis
SET started_on = CURRENT_DATE
WHERE started_on IS NULL;

ALTER TABLE emis
    ALTER COLUMN started_on SET NOT NULL;

CREATE TABLE IF NOT EXISTS emi_installments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emi_id BIGINT NOT NULL REFERENCES emis(id) ON DELETE CASCADE,
    due_date DATE NOT NULL,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'PAID')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_emi_installment_due_date UNIQUE (emi_id, due_date)
);

ALTER TABLE expenses
    ADD COLUMN IF NOT EXISTS emi_installment_id BIGINT;

ALTER TABLE expenses
    ADD CONSTRAINT fk_expenses_emi_installment
        FOREIGN KEY (emi_installment_id) REFERENCES emi_installments(id);

ALTER TABLE expenses
    ADD CONSTRAINT uk_expenses_emi_installment UNIQUE (emi_installment_id);

CREATE INDEX IF NOT EXISTS ix_emi_installments_due_status
    ON emi_installments(status, due_date);
