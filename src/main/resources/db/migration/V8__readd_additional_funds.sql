CREATE TABLE IF NOT EXISTS additional_funds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(255) NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    fund_date DATE NOT NULL,
    source_description VARCHAR(200) NOT NULL,
    purpose VARCHAR(500),
    status VARCHAR(20) NOT NULL CHECK (status IN ('AVAILABLE', 'INACTIVE')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE expense_funding_allocations
    ADD COLUMN IF NOT EXISTS additional_fund_id BIGINT REFERENCES additional_funds(id);

ALTER TABLE expense_funding_allocations
    DROP CONSTRAINT IF EXISTS ck_allocation_source_reference;

ALTER TABLE expense_funding_allocations
    ADD CONSTRAINT ck_allocation_source_reference CHECK (
        (funding_source = 'SALARY'
            AND salary_id IS NOT NULL
            AND opening_balance_id IS NULL
            AND additional_fund_id IS NULL
            AND borrowed_fund_id IS NULL)
        OR (funding_source = 'CARRY_FORWARD'
            AND salary_id IS NULL
            AND opening_balance_id IS NOT NULL
            AND additional_fund_id IS NULL
            AND borrowed_fund_id IS NULL)
        OR (funding_source = 'ADDITIONAL'
            AND salary_id IS NULL
            AND opening_balance_id IS NULL
            AND additional_fund_id IS NOT NULL
            AND borrowed_fund_id IS NULL)
        OR (funding_source = 'BORROWED'
            AND salary_id IS NULL
            AND opening_balance_id IS NULL
            AND additional_fund_id IS NULL
            AND borrowed_fund_id IS NOT NULL)
    );

ALTER TABLE expense_funding_allocations
    DROP CONSTRAINT IF EXISTS ck_expense_funding_allocations_funding_source;

ALTER TABLE expense_funding_allocations
    ADD CONSTRAINT ck_expense_funding_allocations_funding_source
        CHECK (funding_source IN ('SALARY', 'CARRY_FORWARD', 'ADDITIONAL', 'BORROWED'));

ALTER TABLE expense_funding_allocations
    DROP CONSTRAINT IF EXISTS uk_expense_additional_source;

ALTER TABLE expense_funding_allocations
    ADD CONSTRAINT uk_expense_additional_source UNIQUE (expense_id, additional_fund_id);

CREATE INDEX IF NOT EXISTS ix_additional_funds_user_date
    ON additional_funds(user_id, fund_date);

CREATE INDEX IF NOT EXISTS ix_additional_funds_user_status_date
    ON additional_funds(user_id, status, fund_date);
