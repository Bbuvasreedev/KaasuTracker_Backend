CREATE TABLE IF NOT EXISTS app_users (
    id VARCHAR(255) PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    base_salary NUMERIC(12, 2),
    threshold_percentage NUMERIC(5, 2),
    language_pref VARCHAR(20),
    CONSTRAINT uk_app_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount NUMERIC(12, 2) NOT NULL,
    category VARCHAR(100) NOT NULL,
    merchant VARCHAR(150),
    description VARCHAR(500),
    expense_date DATE NOT NULL,
    receipt_url VARCHAR(2048),
    is_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    user_id VARCHAR(255) NOT NULL REFERENCES app_users(id),
    refunded_amount NUMERIC(12, 2) NOT NULL DEFAULT 0
);

ALTER TABLE expenses
    ADD COLUMN IF NOT EXISTS refunded_amount NUMERIC(12, 2) NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS monthly_salaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(255) NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    salary_year INTEGER NOT NULL CHECK (salary_year BETWEEN 1 AND 9999),
    salary_month INTEGER NOT NULL CHECK (salary_month BETWEEN 1 AND 12),
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_monthly_salary_user_period UNIQUE (user_id, salary_year, salary_month)
);

CREATE TABLE IF NOT EXISTS additional_funds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(255) NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    fund_date DATE NOT NULL,
    source_description VARCHAR(200) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('AVAILABLE', 'INACTIVE')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS borrowed_funds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(255) NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    fund_date DATE NOT NULL,
    source_description VARCHAR(200) NOT NULL,
    purpose VARCHAR(500),
    outstanding_repayment_balance NUMERIC(12, 2)
        CHECK (outstanding_repayment_balance IS NULL OR outstanding_repayment_balance >= 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('AVAILABLE', 'INACTIVE')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS monthly_opening_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(255) NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    opening_year INTEGER NOT NULL CHECK (opening_year BETWEEN 1 AND 9999),
    opening_month INTEGER NOT NULL CHECK (opening_month BETWEEN 1 AND 12),
    amount NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_opening_balance_user_period UNIQUE (user_id, opening_year, opening_month)
);

CREATE TABLE IF NOT EXISTS expense_funding_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_id BIGINT NOT NULL REFERENCES expenses(id) ON DELETE CASCADE,
    funding_source VARCHAR(20) NOT NULL
        CHECK (funding_source IN ('SALARY', 'CARRY_FORWARD', 'ADDITIONAL', 'BORROWED')),
    salary_id BIGINT REFERENCES monthly_salaries(id),
    opening_balance_id BIGINT REFERENCES monthly_opening_balances(id),
    additional_fund_id BIGINT REFERENCES additional_funds(id),
    borrowed_fund_id BIGINT REFERENCES borrowed_funds(id),
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_allocation_source_reference CHECK (
        (funding_source = 'SALARY'
            AND salary_id IS NOT NULL
            AND opening_balance_id IS NULL
            AND additional_fund_id IS NULL
            AND borrowed_fund_id IS NULL)
        OR (funding_source = 'CARRY_FORWARD'
            AND salary_id IS NULL
            AND opening_balance_id IS NOT NULL
            AND additional_fund_id IS NULL
            AND borrowed_fund_id IS NULL)
        OR (funding_source = 'ADDITIONAL'
            AND salary_id IS NULL
            AND opening_balance_id IS NULL
            AND additional_fund_id IS NOT NULL
            AND borrowed_fund_id IS NULL)
        OR (funding_source = 'BORROWED'
            AND salary_id IS NULL
            AND opening_balance_id IS NULL
            AND additional_fund_id IS NULL
            AND borrowed_fund_id IS NOT NULL)
    ),
    CONSTRAINT uk_expense_salary_source UNIQUE (expense_id, salary_id),
    CONSTRAINT uk_expense_carry_source UNIQUE (expense_id, opening_balance_id),
    CONSTRAINT uk_expense_additional_source UNIQUE (expense_id, additional_fund_id),
    CONSTRAINT uk_expense_borrowed_source UNIQUE (expense_id, borrowed_fund_id)
);

CREATE INDEX IF NOT EXISTS ix_additional_funds_user_date
    ON additional_funds(user_id, fund_date);

CREATE INDEX IF NOT EXISTS ix_borrowed_funds_user_date
    ON borrowed_funds(user_id, fund_date);

CREATE INDEX IF NOT EXISTS ix_expense_allocations_source
    ON expense_funding_allocations(funding_source, salary_id, opening_balance_id, additional_fund_id, borrowed_fund_id);

CREATE INDEX IF NOT EXISTS ix_expense_allocations_expense
    ON expense_funding_allocations(expense_id);
